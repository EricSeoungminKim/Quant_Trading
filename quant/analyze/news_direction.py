"""뉴스 방향 판정 — **좁고 정밀한 거부권**이지 감성 분석이 아니다.

## 무엇을 고치려는 것인가

`news_momentum` 은 `EVENT` 태그가 붙은 종목을 개장 직후 매수한다. 그 태그는
`render.candidates_line` 의 `today_articles > 0` 에서 나온다 — 즉 **"오늘 기사가
한 건이라도 있다"가 "개장에 사라"가 된다.**

원래 설계는 그렇지 않았다. 전략 docstring 은 "뉴스 판정은 08:40 daily-brief 의
Claude 세션이 이미 끝냈다"고 전제한다. 2026-08-13 에 회사 리포트 의존을 끊고
`own_brief.sh` 로 갈아치우면서 **그 판정 주체가 통째로 사라졌는데 태그 조건은
그대로 남았다.** 실측 피해: 펄어비스 -13,580원, 대신증권 -14,904원.

## 왜 감성 분석이 아니라 거부권인가

실제 우리 데이터를 보면 헤드라인은 대체로 **섞여 있다**. 대신증권 그날 기사:

    "'어닝 서프라이즈'...상반기 순이익 165% 급증"          ← 호재
    "어닝 서프라이즈… 목표주가는 4만원으로 하향 - SK증권"   ← 악재
    "어닝서프라이즈 달성했는데…목표주가 '하향' 이유는?"      ← 악재

호재 키워드 매칭("어닝 서프라이즈")은 이걸 사고, 일반 감성 점수는 LLM 없이
믿을 수 없다. 그래서 **명백한 악재 표지 하나만 보고 거부**한다.

비대칭이 이 설계의 근거다: 호재를 놓치면 안 사는 것뿐(비용 0)이지만, 악재를
호재로 오인하면 돈을 잃는다. 그러니 **애매하면 사지 않는 쪽**으로 판단한다.

## 한계 (과대평가하지 말 것)

이건 좁은 규칙이라 **대부분의 악재를 놓친다.** "펄어비스 어닝쇼크", "목표가
하향" 같은 명시적 표지가 제목에 있을 때만 잡는다. 본문은 읽지 않는다.
제대로 된 방향 판정은 Phase 7 의 판단 리더보드에서 LLM 이 도전자로 들어와
결정론적 베이스라인을 이겨야 승격되는 방식으로 온다. 그때까지의 임시 방벽이다.
"""
from __future__ import annotations

import re

# 명백한 악재 표지. **정밀도 우선** — 애매한 말은 넣지 않는다.
# 각 항목은 실제 우리 저장소 기사에서 확인한 표현이거나, 뜻이 하나뿐인 사건이다.
_BEARISH = [
    # 애널리스트 하향 — 2026-08-13 손실 종목 둘 다에 있었다
    (re.compile(r"목표(?:주)?가[^\n]{0,12}(?:하향|하양|내려|낮춰|낮춤)"), "목표가 하향"),
    (re.compile(r"투자의견[^\n]{0,10}(?:하향|축소|매도)"), "투자의견 하향"),
    # 실적 충격
    (re.compile(r"어닝\s*쇼크"), "어닝쇼크"),
    (re.compile(r"(?:영업)?적자\s*(?:전환|확대|지속)"), "적자"),
    (re.compile(r"실적\s*(?:쇼크|부진|급감)"), "실적 부진"),
    # 자본 희석·구조조정
    (re.compile(r"유상증자"), "유상증자"),
    (re.compile(r"무상감자|감자\s*결정"), "감자"),
    (re.compile(r"전환사채|CB\s*발행"), "전환사채"),
    # 규제·사법
    (re.compile(r"상장\s*폐지|상폐"), "상장폐지"),
    (re.compile(r"거래\s*정지"), "거래정지"),
    (re.compile(r"횡령|배임"), "횡령·배임"),
    (re.compile(r"압수수색|검찰\s*수사"), "수사"),
    (re.compile(r"불성실\s*공시"), "불성실공시"),
    (re.compile(r"리콜|결함\s*은폐"), "리콜"),
    # 지분 이탈
    (re.compile(r"블록딜|시간외\s*대량매매"), "블록딜"),
    (re.compile(r"지분\s*(?:전량\s*)?매각"), "지분 매각"),
]


def bearish_marker(title: str) -> str | None:
    """제목에서 발견된 첫 악재 표지 이름. 없으면 None.

    이름을 돌려주는 이유: 리포트가 **왜 거부됐는지** 보여줘야 한다. "점수가
    낮아서"는 사람이 검증할 수 없고, 규칙이 틀렸을 때 고칠 수도 없다.
    """
    if not title:
        return None
    for pattern, name in _BEARISH:
        if pattern.search(title):
            return name
    return None


def scan(titles: list[str]) -> list[str]:
    """제목 목록에서 발견된 악재 표지들(중복 제거, 발견 순서 유지)."""
    found: list[str] = []
    for t in titles or []:
        name = bearish_marker(t)
        if name and name not in found:
            found.append(name)
    return found
